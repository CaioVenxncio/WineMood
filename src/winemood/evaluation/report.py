def _figures(report: dict[str, Any], ctx: _Ctx, out_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from winemood.analysis.plots import MUTED, OKABE_ITO, _save, _style

    _style()
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = [r for r in report["test_t1"] if r["split"] == "grouped_v1"]
    if rows:
        fig, ax = plt.subplots(figsize=(7, 0.45 * len(rows) + 1.2))
        rows = sorted(rows, key=lambda r: r["mae"]["estimate"], reverse=True)
        for i, r in enumerate(rows):
            m = r["mae"]
            ax.errorbar(
                m["estimate"],
                i,
                xerr=[[m["estimate"] - m["ci95_low"]], [m["ci95_high"] - m["estimate"]]],
                fmt="o",
                color=OKABE_ITO[0],
                capsize=3,
            )
        ax.set_yticks(range(len(rows)), [r["experiment"] for r in rows], fontsize=8)
        ax.set_xlabel("Test MAE (points), 95% cluster-bootstrap CI")
        ax.grid(axis="x", color="#e5e5e5")
        ax.grid(axis="y", visible=False)
        ax.set_title("T1 test MAE (grouped_v1)")
        _save(fig, out_dir / "test_mae_forest.png")
    ea = report.get("error_analysis") or {}
    if ea.get("models"):
        fig, ax = plt.subplots(figsize=(8, 3.6))
        for i, (exp_id, m) in enumerate(ea["models"].items()):
            xs = [float(r["bin"]) for r in m["by_true_score"]]
            ax.plot(
                xs,
                [r["mean_residual"] for r in m["by_true_score"]],
                marker="o",
                ms=3,
                color=OKABE_ITO[i % 7],
                label=exp_id,
            )
        ax.axhline(0, color=MUTED, lw=0.8)
        ax.set_xlabel("True score")
        ax.set_ylabel("Mean residual (pred - true)")
        ax.set_title("Residual by true score (test): regression towards the mean")
        ax.legend(fontsize=7)
        _save(fig, out_dir / "residual_by_true_score.png")
        fig, ax = plt.subplots(figsize=(8, 3.4))
        for i, (exp_id, m) in enumerate(ea["models"].items()):
            ax.plot(
                range(len(m["by_length_decile"])),
                [r["mae"] for r in m["by_length_decile"]],
                marker="o",
                ms=3,
                color=OKABE_ITO[i % 7],
                label=exp_id,
            )
        ax.set_xlabel("Review-length decile (1 = shortest)")
        ax.set_ylabel("MAE (points)")
        ax.set_title("Test MAE by review length")
        ax.legend(fontsize=7)
        _save(fig, out_dir / "mae_by_length.png")
    t2 = [
        r
        for r in report["test_classification"]
        if r["task"] == "T2" and "majority" not in r["experiment"]
    ]
    if t2:
        best = max(t2, key=lambda r: r["macro_f1"]["estimate"])
        cm = np.asarray(best["confusion_matrix"], dtype=float)
        cm = cm / cm.sum(axis=1, keepdims=True).clip(min=1)
        fig, ax = plt.subplots(figsize=(5.2, 4.4))
        ax.imshow(cm, cmap="Blues", vmin=0, vmax=1)
        names = [n.replace("_or_", "/\n").replace("_", " ") for n in best["class_names"]]
        ax.set_xticks(range(len(names)), names, fontsize=7)
        ax.set_yticks(range(len(names)), names, fontsize=7)
        for i in range(len(names)):
            for j in range(len(names)):
                ax.text(
                    j,
                    i,
                    f"{cm[i, j]:.2f}",
                    ha="center",
                    va="center",
                    fontsize=7,
                    color="white" if cm[i, j] > 0.5 else "black",
                )
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")
        ax.grid(False)
        ax.set_title(f"Row-normalised confusion, {best['experiment']} (test)")
        _save(fig, out_dir / "confusion_t2.png")


def build_report(runner, docs_dir: Path) -> Path:
    ctx = _Ctx(runner)
    selection_path = ctx.results / "selection.json"
    selection = read_json(selection_path) if selection_path.is_file() else {}
    validation_rows = []
    for exp_id, res in ctx.val.items():
        task = ctx.plan.tasks[res["task"]]
        vm = res["validation_metrics"]
        validation_rows.append(
            {
                "experiment": exp_id,
                "task": res["task"],
                "split": res["split"],
                "n_configs": res["n_configs"],
                "metric": task.selection_metric,
                "value": vm[task.selection_metric],
                "seed_std": vm.get("mae_seed_std"),
                "n_seeds": len(res.get("seeds") or [1]),
            }
        )
    report = {
        "generated_at": pd.Timestamp.now("UTC").isoformat(timespec="seconds"),
        "bootstrap": {"resamples": ctx.n, "unit": "split group", "seed": ctx.seed},
        "validation": validation_rows,
        "validation_ablations": _validation_ablations(ctx),
        "selection": selection,
        "test_t1": _t1_test_rows(ctx),
        "test_classification": _cls_test_rows(ctx),
        "hypotheses": _hypotheses(ctx) if ctx.test else {},
        "error_analysis": _error_analysis(ctx, selection.get("final_model")) if ctx.test else {},
        "interpretation": _interpretation(ctx),
        "test_prediction_aggregates": _prediction_aggregates(ctx) if ctx.test else {},
        "test_access_log": logged_accesses(ctx.results),
    }
    write_json(ctx.results / "report.json", report)
    fig_dir = docs_dir / "figures" / "results"
    _figures(report, ctx, fig_dir)
    out = docs_dir / "results-tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(_render(report, "figures/results"), encoding="utf-8")
    return out
